/** Stages 31-80 replay map ((n - 31) % 30) turned: 'T' transposes (mirrors on screen), 'F' flips left-right. */
export function stageMapRef(n) {
  if (n <= 30) return { map: n - 1, tf: '' };
  const k = (n - 31) % 30;
  return { map: k, tf: n <= 60 ? 'T' : 'TF' };
}
