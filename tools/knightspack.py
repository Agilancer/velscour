"""Unpack VELSCOUR_Hulking_Castle_Knights_100_Sprites.zip (50 hulking knights and 50 boss knights, native Grim Nocturne pixel art)
into the enemy art pipeline.

    python tools/knightspack.py <VELSCOUR_Hulking_Castle_Knights_100_Sprites.zip>
    python tools/process_assets.py enemies hulking_knights

The pack's individual sprites are already cut and trimmed, so nothing is sliced here: each of its 10 sheets (five of
knights by castle wing, five of boss knights) becomes one folder, assets/source/enemies/hulking_knights/<sheet>/<id>.png,
which process_assets packs into one atlas, stored 1:1 (NATIVE_SETS: pixel art is not resampled). The pack's suggested
pivots mark one foot, not the stance's centre, so process_assets finds the feet column as for every set. The roster (names,
wings, liveries, native heights) is written to src/data/horrorsroster.js, which src/data/phobos.js turns into Act III's
bestiary entries (phx_hk_*), recoloured to the livery of the wing they stand in (LIVERY). The zip is read as data only: just the PNG sprites and the roster/notes come out of it.
"""
import io, json, os, re, sys, zipfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "source", "enemies", "hulking_knights")
ROSTER_JS = os.path.join(ROOT, "src", "data", "knightsroster.js")
SAFE = re.compile(r"^[a-z0-9_]+$")


def folder_of(sheet):
    """sheets/monster/01_charnel_vaults.png -> charnel_vaults; sheets/boss/11_charnel_and_drowned_bosses.png -> bosses_charnel_and_drowned"""
    stem = re.sub(r"^\d+_", "", os.path.splitext(os.path.basename(sheet))[0])
    if stem.endswith("_bosses"):
        stem = "bosses_" + stem[:-len("_bosses")]
    if not SAFE.match(stem):
        raise ValueError("unexpected sheet name %r" % sheet)
    return stem


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    z = zipfile.ZipFile(sys.argv[1])
    roster_in = json.loads(z.read("roster.json"))
    os.makedirs(OUT, exist_ok=True)
    for meta in ("roster.json", "roster.csv", "README.txt", "SHEET_CRITIQUE.md"):
        if meta in z.namelist():
            with open(os.path.join(OUT, meta), "wb") as f:
                f.write(z.read(meta))
    groups = {}
    for e in roster_in:
        if not SAFE.match(e["id"]) or e["kind"] not in ("knight", "boss"):
            raise ValueError("unexpected roster entry %r" % e.get("id"))
        groups.setdefault(folder_of(e["sheet"]), []).append(e)
    roster = []
    for folder in sorted(groups, key=lambda k: groups[k][0]["id"]):
        items = sorted(groups[folder], key=lambda e: e["id"])
        d = os.path.join(OUT, folder)
        os.makedirs(d, exist_ok=True)
        for f in os.listdir(d):
            if f.endswith((".png", ".json")): os.remove(os.path.join(d, f))
        for i, e in enumerate(items):
            img = Image.open(io.BytesIO(z.read(e["sprite"]))).convert("RGBA")
            img.load()
            fn = e["id"] + ".png"
            img.save(os.path.join(d, fn), optimize=True)
            roster.append({"id": e["id"], "name": e["name"], "kind": e["kind"], "wing": e["suggested_castle_wing"],
                           "livery": e["livery"], "weapon": e["weapon_brief"], "sheet": "hulking_knights/" + folder, "i": i, "ap": e["native_height_ap"],
                           "suggest": e["suggested_world_height_px"], "aspect": round(img.height / img.width, 3)})
        print("%-34s %d sprites" % (folder, len(items)))
    with open(ROSTER_JS, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/knightspack.py from VELSCOUR_Hulking_Castle_Knights_100_Sprites.zip: do not edit.\n")
        f.write("export const KNIGHTS_ROSTER = [\n")
        for r in roster:
            f.write("  " + json.dumps(r, ensure_ascii=False) + ",\n")
        f.write("];\n")
    print("%d sprites, roster -> %s" % (len(roster), ROSTER_JS))


if __name__ == "__main__":
    main()
