// Bake the Ethereal Wyrm of the Eternal Breach (tools/breachdragon3d.html) into the sheets the game draws
// (src/gfx/breachdragon.js): assets/sprites/breach_dragon/body.webp (segment and tail, 24 headings x 3 layers),
// parts.webp (heads and claws cut from the set 2 dragons) and dragon.json.
// Needs the repo served (python -m http.server 8123) and three.js from jsDelivr, or THREE_DIR (see gunner3d_bake.js).
//   node tools/breachdragon3d_bake.js            # bake
//   node tools/breachdragon3d_bake.js preview    # a contact sheet -> tools/tests/out/breachdragon3d_preview.png
//   node tools/breachdragon3d_bake.js parts      # the heads and legs cut, marked -> tools/tests/out/breachdragon_parts.png
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const BASE = process.env.BASE_URL || 'http://localhost:8123';
const ROOT = path.resolve(__dirname, '..');
const data = (u) => Buffer.from(u.split(',')[1], 'base64');
(async () => {
  const browser = await chromium.launch({ args: (process.env.CHROMIUM_ARGS || '').split(' ').filter(Boolean) });
  const page = await browser.newPage();
  page.on('console', (m) => ['error', 'warning'].includes(m.type()) && console.log('[page]', m.text()));
  page.on('pageerror', (e) => console.log('[page]', e.message));
  if (process.env.THREE_DIR) {
    await page.route('https://cdn.jsdelivr.net/npm/three@0.170.0/**', (route) => {
      const f = path.join(process.env.THREE_DIR, new URL(route.request().url()).pathname.replace(/^\/npm\/three@0\.170\.0\//, ''));
      return fs.existsSync(f) ? route.fulfill({ status: 200, contentType: 'text/javascript', body: fs.readFileSync(f) }) : route.fulfill({ status: 404, body: '' });
    });
  }
  await page.goto(`${BASE}/tools/breachdragon3d.html?bake`);
  await page.waitForFunction(() => window.DRAGON3D, null, { timeout: 60000 });
  if (process.argv[2] === 'parts') {
    const u = await page.evaluate(() => window.DRAGON3D.partsPreview(3));
    const out = path.join(ROOT, 'tools/tests/out'); fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, 'breachdragon_parts.png'), data(u));
    console.log('parts -> tools/tests/out/breachdragon_parts.png');
  } else if (process.argv[2] === 'preview') {
    const u = await page.evaluate(() => window.DRAGON3D.preview(3));
    const out = path.join(ROOT, 'tools/tests/out'); fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, 'breachdragon3d_preview.png'), data(u));
    console.log('preview -> tools/tests/out/breachdragon3d_preview.png');
  } else {
    const r = await page.evaluate(() => window.DRAGON3D.bake());
    const dir = path.join(ROOT, 'assets/sprites/breach_dragon');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'body.webp'), data(r.body));
    fs.writeFileSync(path.join(dir, 'parts.webp'), data(r.parts));
    fs.writeFileSync(path.join(dir, 'dragon.json'), JSON.stringify({ _: 'generated by tools/breachdragon3d_bake.js; do not edit', ...r.meta }));
    const kb = (f) => (fs.statSync(path.join(dir, f)).size / 1024).toFixed(0) + ' KB';
    console.log(`body ${kb('body.webp')}, parts ${kb('parts.webp')} (${Object.keys(r.meta.heads).length} heads, ${Object.keys(r.meta.claws).length} claws) in ${r.ms} ms`);
  }
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
