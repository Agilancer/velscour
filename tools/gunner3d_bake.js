// Bake the Gunner's turrets and Bombing Run biplane (tools/gunner3d.html, models in tools/gunner3d.js) into the sheets
// the game draws (src/gfx/gunner3d.js): assets/sprites/gunner/<turret kind>.webp/json and biplane.webp/json.
// Needs the repo served (python -m http.server 8123) and three.js: jsDelivr, or a local copy of the npm package
// (THREE_DIR=<dir holding build/ and examples/>, e.g. from `npm pack three@0.170.0`) when the CDN is out of reach.
//   node tools/gunner3d_bake.js            # bake
//   node tools/gunner3d_bake.js preview    # a contact sheet -> tools/tests/out/gunner3d_preview.png
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const BASE = process.env.BASE_URL || 'http://localhost:8123';
const ROOT = path.resolve(__dirname, '..');
const data = (u) => Buffer.from(u.split(',')[1], 'base64');
(async () => {
  const browser = await chromium.launch({ args: (process.env.CHROMIUM_ARGS || '').split(' ').filter(Boolean) });
  const page = await browser.newPage();
  page.on('console', (m) => ['error', 'warning'].includes(m.type()) && console.log('[page]', m.text()));
  page.on('pageerror', (e) => console.log('[page]', e.message));
  if (process.env.THREE_DIR) {
    await page.route('https://cdn.jsdelivr.net/npm/three@0.170.0/**', (route) => {
      const f = path.join(process.env.THREE_DIR, new URL(route.request().url()).pathname.replace(/^\/npm\/three@0\.170\.0\//, ''));
      return fs.existsSync(f) ? route.fulfill({ status: 200, contentType: 'text/javascript', body: fs.readFileSync(f) }) : route.fulfill({ status: 404, body: '' });
    });
  }
  await page.goto(`${BASE}/tools/gunner3d.html?bake`);
  await page.waitForFunction(() => window.GUNNER3D, null, { timeout: 60000 });
  if (process.argv[2] === 'preview') {
    const u = await page.evaluate(() => window.GUNNER3D.preview(3));
    const out = path.join(ROOT, 'tools/tests/out'); fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, 'gunner3d_preview.png'), data(u));
    console.log('preview -> tools/tests/out/gunner3d_preview.png');
  } else {
    const r = await page.evaluate(() => window.GUNNER3D.bake());
    const dir = path.join(ROOT, 'assets/sprites/gunner');
    fs.mkdirSync(dir, { recursive: true });
    for (const [k, v] of Object.entries(r.out)) {
      fs.writeFileSync(path.join(dir, `${k}.webp`), data(v.sheet));
      fs.writeFileSync(path.join(dir, `${k}.json`), JSON.stringify({ _: 'generated by tools/gunner3d_bake.js; do not edit', ...v.meta }));
      console.log(`${k}: ${v.meta.dirs} turns x ${v.meta.frames} frames, ${(fs.statSync(path.join(dir, `${k}.webp`)).size / 1024).toFixed(0)} KB`);
    }
    console.log(`baked in ${r.ms} ms`);
  }
  await browser.close();
})();
