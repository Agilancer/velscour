"""Import the generated replacement sprites. Run: python tools/replacementart.py.

Source PNGs and catalog are authoritative. Only crop, uniformly downscale and pack;
preserve the generated alpha. Adaptive gutter cuts accommodate the source grids.
Requires Pillow and numpy (also used by process_assets.py).
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source/replacements'
OUT = ROOT / 'assets/sprites/replacements'


def cuts(alpha, count, axis):
    length = alpha.shape[axis]
    occupancy = (alpha > 32).sum(axis=1-axis)
    result = [0]
    for n in range(1, count):
        center = round(length * n / count)
        radius = round(length / count * .2)
        candidates = range(max(result[-1]+1, center-radius), min(length, center+radius+1))
        result.append(min(candidates, key=lambda p: (occupancy[p], abs(p-center))))
    return result + [length]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    catalog = json.loads((SOURCE / 'catalog.json').read_text())
    pieces, definitions = [], []
    for sheet in catalog['sheets']:
        image = Image.open(SOURCE / sheet['file']).convert('RGBA')
        alpha = np.asarray(image)[:, :, 3]
        ys = cuts(alpha, sheet['rows'], 0)
        for entry in sheet['entries']:
            row, col = divmod(entry['cell'], sheet['columns'])
            xs = cuts(alpha[ys[row]:ys[row+1]], sheet['columns'], 1)
            rect = tuple(entry.get('rect', (xs[col], ys[row], xs[col+1], ys[row+1])))
            crop = image.crop(rect)
            # Ignore only almost invisible alpha when locating the crop; keep RGBA unchanged.
            bbox = crop.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
            if not bbox:
                raise ValueError('Empty sprite: ' + entry['id'])
            crop = crop.crop(bbox)
            limit = 320 if entry['kind'] == 'boss' else 96 if entry['kind'] == 'icon' else 160
            k = min(1, limit / max(crop.size))
            crop = crop.resize((max(1, round(crop.width*k)), max(1, round(crop.height*k))), Image.Resampling.NEAREST)
            # 2px transparent gutters isolate every packed sprite, including alpha edge pixels.
            piece = Image.new('RGBA', (crop.width+4, crop.height+4))
            piece.paste(crop, (2, 2))
            pieces.append((entry, piece, rect))
            definitions.append({'id':'va_'+entry['id'], 'name':entry['id'].replace('_', ' ').title(), 'h':entry['height']})
    width, x, y, rowh = 1024, 0, 0, 0
    meta = {}
    positions = []
    for entry, piece, rect in pieces:
        if x + piece.width > width:
            x, y, rowh = 0, y+rowh, 0
        meta[entry['id']] = {'x':x, 'y':y, 'w':piece.width, 'h':piece.height, 'fx':.5, 'sourceRect':rect}
        positions.append((piece, x, y))
        x += piece.width
        rowh = max(rowh, piece.height)
    atlas = Image.new('RGBA', (width, y+rowh))
    for piece, x, y in positions:
        atlas.paste(piece, (x,y))
    atlas.save(OUT / 'atlas.webp', lossless=True, method=6)
    (OUT / 'atlas.json').write_text(json.dumps(meta, indent=2)+'\n')
    (ROOT / 'src/data/replacementart.js').write_text('// Generated by tools/replacementart.py; edit the source catalog.\nexport const REPLACEMENT_ART = '+json.dumps(definitions, separators=(',', ':'))+';\n')
    print(f'{len(meta)} sprites, {atlas.width}x{atlas.height}, {(OUT / "atlas.webp").stat().st_size//1024} KB')


if __name__ == '__main__':
    main()
