// Bake the Bellmourn treasure chest (tools/chest3d.html, assets/source/chest3d/chest.glb) into the sheet the game
// draws: assets/sprites/chest3d.webp + .json, eight frames of the lid opening from the iso camera (src/gfx/chest3d.js).
// Needs the repo served (python -m http.server 8123) and Pillow (lossless WebP, a short palette and a dark outline
// like the painted packs).   node tools/chest3d_bake.js
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const { chromium } = require('playwright');
const BASE = process.env.BASE_URL || 'http://localhost:8123', ROOT = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ args: (process.env.CHROMIUM_ARGS || '--use-gl=swiftshader --enable-unsafe-swiftshader').split(' ').filter(Boolean) });
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.log('[page]', e.message));
  await page.goto(`${BASE}/tools/chest3d.html`);
  await page.waitForFunction(() => window.CHEST3D, null, { timeout: 60000 });
  const r = await page.evaluate(() => window.CHEST3D.bake());
  const png = path.join(ROOT, 'assets/sprites/chest3d.png'), out = path.join(ROOT, 'assets/sprites/chest3d.webp');
  fs.writeFileSync(png, Buffer.from(r.sheet.split(',')[1], 'base64'));
  execFileSync('python3', ['-c', `
import sys, numpy as np
from PIL import Image
im = Image.open(sys.argv[1]).convert('RGBA'); a = np.asarray(im).copy()
hard = a[..., 3] > 110
q = np.asarray(Image.fromarray(a[..., :3], 'RGB').quantize(64, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB'))
o = np.dstack([q, (hard * 255).astype(np.uint8)])
p = np.pad(hard, 1); ring = (p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:]) & ~hard
o[ring] = (14, 11, 10, 235); o[~hard & ~ring] = 0
Image.fromarray(o, 'RGBA').save(sys.argv[2], 'WEBP', lossless=True, method=6)
`, png, out]);
  fs.unlinkSync(png);
  fs.writeFileSync(path.join(ROOT, 'assets/sprites/chest3d.json'), JSON.stringify({ _: 'generated by tools/chest3d_bake.js; do not edit', ...r.meta }));
  console.log('chest3d:', r.meta, (fs.statSync(out).size / 1024).toFixed(0), 'KB');
  await browser.close();
})();
