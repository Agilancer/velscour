// Bake Varrow's great axe (tools/varrowaxe3d.html, model in tools/varrowaxe3d.js) into the sheet the game draws:
// assets/sprites/npc/varrow_axe.webp + .json (32 turns, their rune layer, the rack; src/gfx/varrowaxe.js).
// Needs the repo served (python -m http.server 8123) and jsDelivr (three.js, for this tool only).
//   node tools/varrowaxe3d_bake.js            # bake
//   node tools/varrowaxe3d_bake.js preview    # a turntable contact sheet -> tools/tests/out/varrowaxe3d_turntable.png
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const BASE = process.env.BASE_URL || 'http://localhost:8123';
const ROOT = path.resolve(__dirname, '..');
const data = (u) => Buffer.from(u.split(',')[1], 'base64');
(async () => {
  const browser = await chromium.launch({ args: (process.env.CHROMIUM_ARGS || '').split(' ').filter(Boolean) });
  const page = await browser.newPage();
  page.on('console', (m) => ['error', 'warning'].includes(m.type()) && console.log('[page]', m.text()));
  page.on('pageerror', (e) => console.log('[page]', e.message));
  await page.goto(`${BASE}/tools/varrowaxe3d.html?bake`);
  await page.waitForFunction(() => window.AXE3D, null, { timeout: 60000 });
  if (process.argv[2] === 'preview') {
    // 8 turns x 3 looks (chapter 0, 6, 11), magnified, on one sheet
    const u = await page.evaluate(async () => {
      const shots = [];
      for (const ch of [0, 6, 11]) for (let i = 0; i < 8; i++) shots.push(await new Promise((res) => { const im = new Image(); im.onload = () => res(im); im.src = window.AXE3D.preview((i / 8) * Math.PI * 2, ch, 4); }));
      const c = document.createElement('canvas'), w = shots[0].width, h = shots[0].height;
      c.width = w * 8; c.height = h * 3;
      const g = c.getContext('2d'); g.fillStyle = '#3a4a2c'; g.fillRect(0, 0, c.width, c.height);
      shots.forEach((im, i) => g.drawImage(im, (i % 8) * w, Math.floor(i / 8) * h));
      return c.toDataURL('image/png');
    });
    const out = path.join(ROOT, 'tools/tests/out'); fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, 'varrowaxe3d_turntable.png'), data(u));
    console.log('preview -> tools/tests/out/varrowaxe3d_turntable.png');
  } else {
    const r = await page.evaluate(() => window.AXE3D.bake(Number(3), 32));
    const dir = path.join(ROOT, 'assets/sprites/npc');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'varrow_axe.webp'), data(r.sheet));
    fs.writeFileSync(path.join(dir, 'varrow_axe.json'), JSON.stringify({ _: 'generated by tools/varrowaxe3d_bake.js; do not edit', ...r.meta }));
    console.log(`varrow axe: ${r.meta.n} turns at ${r.meta.S}x, ${(fs.statSync(path.join(dir, 'varrow_axe.webp')).size / 1024).toFixed(0)} KB, ${r.ms} ms`);
  }
  await browser.close();
})();
