const CLASS_CHANCE = 0.08;

/**
 * Velscour's level-up line for hero c (after c.level went up): { mood, l1, l2 }.
 * st = { last: mood, used: { pool: [index, ...] } } is the deck, updated in place so the caller can keep it.
 */
export function pickTaunt(c, st, rnd = Math.random) {
  st.used = st.used || {};
  const fill = (s) => s.replace(/\{name\}/g, c.name || 'Hero').replace(/\{class\}/g, (CLASSES[c.classId] || {}).name || 'Hero').replace(/\{level\}/g, c.level);
  const out = (mood, s) => { st.last = mood; const [l1, l2] = fill(s).split('|'); return { mood, l1, l2 }; };
  const draw = (key, n, ok) => { // an unused index of a pool of n, or -1; the pool reshuffles once it is spent
    let used = st.used[key] || (st.used[key] = []);
    let free = [];
    for (let i = 0; i < n; i++) if (!used.includes(i) && ok(i)) free.push(i);
    if (!free.length) { used = st.used[key] = []; for (let i = 0; i < n; i++) if (ok(i)) free.push(i); }
    if (!free.length) return -1;
    const i = free[Math.floor(rnd() * free.length)];
    used.push(i);
    return i;
  };
  const ms = MILESTONES[c.level];
  if (ms) return out(ms[0], ms[1]);
  const next = (MILESTONES[c.level + 1] || [])[0]; // keep clear of the next milestone's mood too
  const cls = CLASS_TAUNTS[c.classId];
  if (cls && rnd() < CLASS_CHANCE) {
    const i = draw('class.' + c.classId, cls.length, (k) => cls[k][0] !== st.last && cls[k][0] !== next);
    if (i >= 0) return out(cls[i][0], cls[i][1]);
  }
  // a new mood, weighted by pool size so every line is about as likely as any other
  const moods = Object.keys(TAUNTS).filter((m) => m !== st.last && m !== next);
  let r = rnd() * moods.reduce((s, m) => s + TAUNTS[m].length, 0), mood = moods[0];
  for (const m of moods) { r -= TAUNTS[m].length; if (r < 0) { mood = m; break; } }
  return out(mood, TAUNTS[mood][draw(mood, TAUNTS[mood].length, () => true)]);
}
